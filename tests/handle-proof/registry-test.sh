set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# shellcheck source=registry.sh
source "${REGISTRY_PROOF_HELPER:-$ROOT/tests/handle-proof/registry.sh}"
PG="${PROOF_RUN_PREFIX:-}cyfr-handle-proof-registry-test-$$"
scratch="$(mktemp -d)"
cleanup() {
  docker rm -f -v "$PG" >/dev/null 2>&1 || true
  rm -rf "$scratch"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

docker run -d --name "$PG" --network none \
  -e POSTGRES_USER=cyfrrun -e POSTGRES_DB=cyfrrun -e POSTGRES_HOST_AUTH_METHOD=trust \
  postgres:16-alpine >/dev/null
closes=$((SECONDS + 60))
until docker exec "$PG" pg_isready -U cyfrrun -d cyfrrun >/dev/null 2>&1; do
  [ "$SECONDS" -lt "$closes" ] || { echo 'FAIL: PostgreSQL did not become ready'; exit 1; }
  sleep 1
done
registry_sql <<'SQL'
CREATE SCHEMA directory;
CREATE TABLE directory.identity_log_entries (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  seq INTEGER NOT NULL CHECK (seq >= 0),
  entry BYTEA NOT NULL
);
INSERT INTO directory.identity_log_entries (seq, entry) VALUES (0, '\x7b7d'), (0, '\x7b7d');
CREATE TABLE directory.default_ids (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
INSERT INTO directory.default_ids DEFAULT VALUES;
CREATE TABLE public.namespaces (id INTEGER PRIMARY KEY, seq INTEGER NOT NULL CHECK (seq >= 0));
INSERT INTO public.namespaces VALUES (1, 0);
SQL

check_restore() {
  local table="$1" field="$2" bad="$3" good="$4" key=1 before answer changed
  before="$(registry_state "$table")"
  answer="$(registry_set "$table" id "$key" "$field" "{\"$field\":$bad}" tamper | tail -n 1)"
  python3 -I -c 'import json, sys; assert json.loads(sys.argv[1]) == {"set": 1, "role": "origin"}' "$answer"
  if [ "$field" = id ]; then key="$bad"; fi
  changed="$(registry_rows "$table" id "$key")"
  python3 -I -c 'import json, sys; rows=json.loads(sys.argv[1])["rows"]; assert len(rows)==1 and rows[0][sys.argv[2]]==int(sys.argv[3])' "$changed" "$field" "$bad"
  changed="$(registry_state "$table")"
  python3 -I -c 'import json, sys; assert json.loads(sys.argv[1])["identity_columns"]==json.loads(sys.argv[2])["identity_columns"]' "$before" "$changed"
  answer="$(registry_set "$table" id "$key" "$field" "{\"$field\":$good}" restore | tail -n 1)"
  python3 -I -c 'import json, sys; assert json.loads(sys.argv[1]) == {"set": 1, "role": "origin"}' "$answer"
  changed="$(registry_state "$table")"
  python3 -I -c 'import json, sys; assert json.loads(sys.argv[1])==json.loads(sys.argv[2])' "$before" "$changed"
  echo "PASS: $table.$field tampers, restores and preserves its identity declaration and constraints"
}

check_restore directory.identity_log_entries id 9007199254740991 1
check_restore directory.identity_log_entries seq -1 0
check_restore directory.default_ids id 9007199254740991 1
check_restore namespaces seq -1 0

before="$(registry_state directory.identity_log_entries)"
if registry_set directory.identity_log_entries id 1 id '{"id":"invalid"}' tamper >"$scratch/out" 2>"$scratch/err"; then
  echo 'FAIL: an invalid identity-column write was accepted'
  exit 1
fi
changed="$(registry_state directory.identity_log_entries)"
python3 -I -c 'import json, sys; assert json.loads(sys.argv[1])==json.loads(sys.argv[2])' "$before" "$changed"
echo 'PASS: a refused write rolls back its row, identity declaration and constraints'

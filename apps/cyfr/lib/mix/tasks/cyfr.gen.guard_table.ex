defmodule Mix.Tasks.Cyfr.Gen.GuardTable do
  @shortdoc "Write the island egress guard's address table from Prima.Cidr"

  @moduledoc """
  Writes `Prima.Cidr.address_table/0` into the island egress guard's
  address table, `apps/locus/keeper/guard/table_gen.go`: the metadata rows
  and the private rows of each family, a private row that is also a
  metadata row left to the metadata rule the guard installs first.

      mix cyfr.gen.guard_table

  `apps/cyfr/test/cyfr/guard_table_test.exs` fails when the file is not
  the render.
  """

  use Boundary, classify_to: Cyfr

  use Mix.Task

  @target "apps/locus/keeper/guard/table_gen.go"

  @impl Mix.Task
  def run(args) do
    Mix.Task.run("compile")

    case args do
      [] ->
        # arca:bypass-ok=E — the guard's table is a tracked file of the repository.
        File.write!(path(), render())
        Mix.shell().info("wrote the address table into #{@target}")

      _other ->
        Mix.raise("usage: mix cyfr.gen.guard_table")
    end
  end

  @doc "The table's absolute path."
  @spec path() :: Path.t()
  def path, do: Path.join(root(), @target)

  @doc "The rows the guard installs, by its variable's name."
  @spec rows() :: [{String.t(), [String.t()]}]
  def rows do
    %{metadata: metadata, private: private} = Prima.Cidr.address_table()
    private = private -- metadata

    [
      {"metadataV4", ipv4(metadata)},
      {"metadataV6", ipv6(metadata)},
      {"privateV4", ipv4(private)},
      {"privateV6", ipv6(private)}
    ]
  end

  @doc "The file's text."
  @spec render() :: String.t()
  def render do
    variables =
      Enum.map_join(rows(), "\n", fn {name, rows} ->
        "var #{name} = []string{\n" <> Enum.map_join(rows, "", &"\t#{inspect(&1)},\n") <> "}\n"
      end)

    """
    // SPDX-License-Identifier: Apache-2.0
    // Copyright 2026 CYFR Works Inc.

    // Code generated by `mix cyfr.gen.guard_table` from Prima.Cidr.address_table/0. DO NOT EDIT.

    package guard

    // The metadata and the private rows of each family, as iptables and
    // ip6tables take them (rules.go).

    #{variables}\
    """
  end

  defp ipv4(rows), do: Enum.reject(rows, &String.contains?(&1, ":"))
  defp ipv6(rows), do: Enum.filter(rows, &String.contains?(&1, ":"))

  defp root, do: Path.expand("../../../../..", __DIR__)
end

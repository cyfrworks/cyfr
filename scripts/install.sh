set -eu

# Install script for cyfr CLI
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/cyfrworks/cyfr/main/scripts/install.sh | sh
#
# Environment variables:
#   CYFR_VERSION              - the exact version to install, a pre-release
#                               such as 0.6.0-alpha.1 included (default: the
#                               latest release that is not a pre-release)
#   CYFR_INSTALL_DIR          - installation directory (default: on the system
#                               the policy block below names, without a
#                               verification bypass, the directory of its
#                               install path; otherwise /opt/homebrew/bin or
#                               /usr/local/bin where writable, else
#                               ~/.local/bin)
#   CYFR_INSTALL_YES          - set to 1 to approve the displayed root commands
#                               without a question; without a terminal, sudo
#                               must then run them without a password prompt
#                               (sudo -n)
#   CYFR_ALLOW_UNVERIFIED     - set to 1 to install without cosign, or without the
#                               release's signature bundle: checksums.txt's
#                               signature is then NOT verified (the checksum is)
#   CYFR_INSECURE_SKIP_VERIFY - set to 1 to skip checksum/signature verification
#                               (NOT recommended; for airgapped/bootstrap edge cases)
#
# Integrity: checksums.txt must carry the release workflow's keyless cosign
# signature for the version installed (the certificate identity exactly
# https://github.com/cyfrworks/cyfr/.github/workflows/release.yml@refs/tags/<version>,
# GitHub Actions' OIDC issuer), as `cyfr update` verifies it in process;
# without cosign or the signature the install refuses unless
# CYFR_ALLOW_UNVERIFIED=1. The archive's SHA-256 checksum is then verified
# against checksums.txt, and the install fails on any mismatch or missing
# tooling. CYFR_INSECURE_SKIP_VERIFY=1 skips both.
#
# Requirements: on the system the policy block names, the bootstrap
# packages the verification needs and the machine lacks come from the
# system's archive before anything is downloaded, and the verified CLI is
# installed root-owned at the policy's install path. Both are root actions:
# the script runs as the person, prints the exact commands, asks on the
# terminal (CYFR_INSTALL_YES=1 answers for it), and then elevates once, to
# a fixed helper (root_helper_text) that takes the machine-wide install
# lock, runs apt and installs only the file whose SHA-256 the person's side
# verified. A verification bypass leaves nothing verified for root to
# install, so under one the CLI is installed as on other systems, which
# install as before and are told what they lack.

GITHUB_REPO="cyfrworks/cyfr"
BINARY_NAME="cyfr"

# BEGIN install policy, generated by scripts/generate-install-policy.py from apps/codex/internal/install/policy.json
POLICY_SYSTEM_ID='ubuntu'
POLICY_SYSTEM_VERSION_ID='26.04'
POLICY_SYSTEM_CODENAME='resolute'
POLICY_SYSTEM_NAME='Ubuntu 26.04 LTS'
POLICY_SYSTEM_ARCHITECTURES='amd64 arm64'
POLICY_UNIVERSE_COMPONENT='universe'
POLICY_UNIVERSE_COMMAND='sudo add-apt-repository universe'
# One bootstrap row a line: the package, the fact that shows it present
# (installed: dpkg reports the package installed, read on the supported
# system alone; commands: one of the comma-separated commands is on PATH),
# its values and whether only Ubuntu's universe component carries it.
POLICY_BOOTSTRAP='ca-certificates installed ca-certificates no
curl commands curl,wget no
cosign commands cosign yes'
POLICY_INSTALL_PATH='/usr/local/bin/cyfr'
POLICY_LOCK_PATH='/run/cyfr-install.lock'
POLICY_LOCK_SECONDS='60'
# END install policy

# Where the system's identity, the person's answers and root's tools come
# from, and the directories a plain install tries, in order, before
# ~/.local/bin. They are assigned here, never read from the environment;
# the test harness sources this file and reassigns them.
OS_RELEASE_PATHS='/etc/os-release /usr/lib/os-release'
TTY_DEVICE=/dev/tty
ROOT_PATH=/usr/sbin:/usr/bin:/sbin:/bin
PLAIN_INSTALL_DIRS='/opt/homebrew/bin /usr/local/bin'

main() {
    os="$(detect_os)"
    arch="$(detect_arch)"
    approval="$(install_approval)"
    as_root=no
    if [ "$(id -u)" = 0 ]; then
        as_root=yes
    fi

    read_system "$os"
    supported=no
    if [ "$os" = "linux" ] && system_supported "$arch"; then
        supported=yes
    fi

    bootstrap_decide "$supported"
    case "$bootstrap_outcome" in
        universe-missing) refuse_universe ;;
        unsupported) refuse_unsupported ;;
    esac

    binary="$BINARY_NAME"
    if [ "$os" = "windows" ]; then
        binary="${BINARY_NAME}.exe"
    fi

    # On the supported system root installs the verified CLI: at the
    # policy's path, or in an explicit CYFR_INSTALL_DIR the person cannot
    # write. A download a bypass leaves unverified is never root's to
    # install, so under a bypass, as on every other system, install_binary
    # installs it, as it always has.
    root_dest=
    if [ "$supported" = yes ] && ! skip_verify && ! allow_unverified; then
        if [ -z "${CYFR_INSTALL_DIR:-}" ]; then
            install_dir="${POLICY_INSTALL_PATH%/*}"
            root_dest="$POLICY_INSTALL_PATH"
        else
            install_dir="$(resolve_install_dir)"
            if [ ! -w "$install_dir" ]; then
                root_dest="$install_dir/$binary"
            fi
        fi
    else
        install_dir="$(resolve_install_dir)"
    fi

    tmpdir="$(mktemp -d)"
    case "$tmpdir" in
        /*) ;;
        *) tmpdir="$(pwd)/$tmpdir" ;;
    esac
    chmod 700 "$tmpdir"
    sudo_cleanup=no
    trap cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    trap 'exit 129' HUP

    helper=none
    requested_packages=
    if [ "$bootstrap_outcome" = install ]; then
        # The packages the verification needs come first; one elevation
        # covers them and, when root installs it, the verified CLI.
        requested_packages="$bootstrap_packages"
        # shellcheck disable=SC2086 # policy package names, one word each
        packages_before="$(installed_packages $requested_packages)"
        agree_to_root_plan "$requested_packages" "$root_dest"
        # shellcheck disable=SC2086 # policy package names, one word each
        with_root_helper "${root_dest:--}" $requested_packages -- install_after_packages
    else
        install_release
    fi
}

# The rest of the installation once root reports the packages installed,
# beside the helper, which waits for the verified CLI when it installs it.
install_after_packages() {
    await_helper packages
    bootstrap_decide yes
    if [ "$bootstrap_outcome" != satisfied ]; then
        # shellcheck disable=SC2086 # policy package names, one word each
        refuse "CYFR could not finish installing $(words $bootstrap_packages). $(completed_changes). Check the messages above, then run \`$(install_command)\` again."
    fi
    install_release
}

install_release() {
    version="$(resolve_version)"

    if [ "$os" = "windows" ]; then
        ext="zip"
    else
        ext="tar.gz"
    fi

    archive="cyfr_${version}_${os}_${arch}.${ext}"
    url="https://github.com/${GITHUB_REPO}/releases/download/${version}/${archive}"
    checksums_url="https://github.com/${GITHUB_REPO}/releases/download/${version}/checksums.txt"
    sig_bundle_url="${checksums_url}.sigstore.json"

    printf "Installing cyfr v%s (%s/%s) to %s\n" "$version" "$os" "$arch" "$install_dir"

    printf "Downloading %s...\n" "$archive"
    download "$url" "$tmpdir/$archive" || refuse_download "$archive" github.com

    printf "Downloading checksums...\n"
    download "$checksums_url" "$tmpdir/checksums.txt" || refuse_download checksums.txt github.com

    verify_signature "$tmpdir" "$sig_bundle_url" "$version"
    verify_checksum "$tmpdir" "$archive"

    printf "Extracting...\n"
    extract "$tmpdir/$archive" "$tmpdir" "$ext"

    if [ -n "$root_dest" ]; then
        install_as_root
    else
        install_binary "$tmpdir/$binary" "$install_dir/$binary"
        printf "\ncyfr v%s installed successfully to %s/%s\n" "$version" "$install_dir" "$binary"
    fi

    migrate_path "$install_dir/$binary"

    check_path "$install_dir"

    if [ "$os" = "darwin" ]; then
        homebrew_tip "$version"
    fi
}

# Hand the verified CLI to root, which copies it to root_dest. A target that
# already holds these bytes, root's mode and its directory's owner is left
# alone, so a rerun of an installed version elevates nothing.
install_as_root() {
    verified_sha="$(file_sha256 "$tmpdir/$binary")"
    if installed_matches "$root_dest" "$verified_sha"; then
        if [ "$helper" = running ]; then
            printf 'done\n' >&3
        fi
        printf "\ncyfr v%s is already installed at %s\n" "$version" "$root_dest"
        return
    fi
    if [ "$helper" = running ]; then
        hand_to_helper "$verified_sha"
    else
        agree_to_root_plan "" "$root_dest"
        with_root_helper "$root_dest" -- hand_to_helper "$verified_sha"
    fi
    printf "\ncyfr v%s installed successfully to %s\n" "$version" "$root_dest"
}

hand_to_helper() {
    printf 'install %s %s\n' "$tmpdir/$binary" "$1" >&3
    await_helper installed
}

# Removes what the run made and invalidates sudo's cached login. It runs on
# every exit the shell sees; with_root_helper's pipeline has returned by
# then, so the helper has exited first.
cleanup() {
    if [ "$sudo_cleanup" = yes ]; then
        sudo -k </dev/null >/dev/null 2>&1 || true
    fi
    rm -rf "$tmpdir"
}

# macOS's closing tip for the version $1 installed. The Homebrew cask
# installs the latest release that is not a pre-release, so it is offered
# for a bare version alone; a pre-release (0.6.0-alpha.1, a version with a
# pre-release part) is told the cask follows the first such release.
homebrew_tip() {
    case "$1" in
        *-*)
            printf "\nThe Homebrew cask follows the first release that is not a pre-release; v%s is a pre-release, installed by this script alone.\n" "$1"
            ;;
        *)
            printf "\nTip: You can also install via Homebrew:\n"
            printf "  brew tap cyfrworks/cyfr && brew install --cask cyfr\n"
            ;;
    esac
}

detect_os() {
    case "$(uname -s)" in
        Linux*)   echo "linux" ;;
        Darwin*)  echo "darwin" ;;
        MINGW*|MSYS*|CYGWIN*) echo "windows" ;;
        *)
            printf "Error: unsupported operating system: %s\n" "$(uname -s)" >&2
            exit 1
            ;;
    esac
}

detect_arch() {
    case "$(uname -m)" in
        x86_64|amd64)   echo "amd64" ;;
        aarch64|arm64)  echo "arm64" ;;
        *)
            printf "Error: unsupported architecture: %s\n" "$(uname -m)" >&2
            exit 1
            ;;
    esac
}

# CYFR_INSTALL_YES=1 approves the displayed root commands; unset or empty
# asks. Any other value is refused rather than read as either.
install_approval() {
    case "${CYFR_INSTALL_YES:-}" in
        "") echo "ask" ;;
        1) echo "yes" ;;
        *)
            printf "Error: CYFR_INSTALL_YES is %s; set it to 1 to approve the displayed commands without a question, or unset it to be asked.\n" "$CYFR_INSTALL_YES" >&2
            exit 1
            ;;
    esac
}

# Sets os_id, os_version_id, os_codename, os_name and os_pretty_name. On
# Linux they come from os-release, read as data and never sourced.
read_system() {
    os_id=
    os_version_id=
    os_codename=
    os_name=
    os_pretty_name=
    case "$1" in
        linux)
            for os_release_path in $OS_RELEASE_PATHS; do
                if [ -f "$os_release_path" ]; then
                    read_os_release "$os_release_path"
                    break
                fi
            done
            ;;
        darwin)
            os_name="macOS"
            os_version_id="$(sw_vers -productVersion 2>/dev/null || true)"
            ;;
        windows)
            os_name="Windows"
            ;;
    esac
}

# Each KEY=VALUE line of the os-release file $1, without its surrounding
# blanks: a value quoted whole in double or single quotes loses the quotes;
# comments, blank lines and other lines are skipped.
read_os_release() {
    while read -r os_line || [ -n "$os_line" ]; do
        case "$os_line" in
            ""|"#"*|=*) continue ;;
            *=*) ;;
            *) continue ;;
        esac
        os_key="${os_line%%=*}"
        os_value="${os_line#*=}"
        case "$os_key" in
            *[!A-Z0-9_]*) continue ;;
        esac
        case "$os_value" in
            \"*\")
                os_value="${os_value#\"}"
                os_value="${os_value%\"}"
                ;;
            \'*\')
                os_value="${os_value#\'}"
                os_value="${os_value%\'}"
                ;;
        esac
        case "$os_key" in
            ID) os_id="$os_value" ;;
            VERSION_ID) os_version_id="$os_value" ;;
            VERSION_CODENAME) os_codename="$os_value" ;;
            NAME) os_name="$os_value" ;;
            PRETTY_NAME) os_pretty_name="$os_value" ;;
        esac
    done <"$1"
}

# Whether read_system's system on architecture $1 is the one the policy
# prepares automatically: the exact id and version, compared as strings, so
# neither a later release nor a number that equals the version is accepted.
system_supported() {
    if [ "$os_id" != "$POLICY_SYSTEM_ID" ] || [ "$os_version_id" != "$POLICY_SYSTEM_VERSION_ID" ]; then
        return 1
    fi
    case " $POLICY_SYSTEM_ARCHITECTURES " in
        *" $1 "*) return 0 ;;
    esac
    return 1
}

# The system's name in refusals.
system_name() {
    if [ -n "$os_pretty_name" ]; then
        printf '%s\n' "$os_pretty_name"
    elif [ -n "$os_name" ] && [ -n "$os_version_id" ]; then
        printf '%s %s\n' "$os_name" "$os_version_id"
    elif [ -n "$os_name" ]; then
        printf '%s\n' "$os_name"
    else
        printf 'Linux\n'
    fi
}

# Whether apt reads the universe component's packages of the system's own
# release (its VERSION_CODENAME, or the policy's), not a pocket, another
# release or a third-party suite that also names a universe component.
universe_enabled() {
    universe_release="${os_codename:-$POLICY_SYSTEM_CODENAME}"
    # shellcheck disable=SC2016 # apt's own format fields, not the shell's
    universe_targets="$(apt-get indextargets --no-release-info --format '$(RELEASE) $(COMPONENT) $(IDENTIFIER)' </dev/null 2>/dev/null)" || return 1
    while IFS= read -r universe_line; do
        if [ "$universe_line" = "$universe_release $POLICY_UNIVERSE_COMPONENT Packages" ]; then
            return 0
        fi
    done <<EOF
$universe_targets
EOF
    return 1
}

# Decides the bootstrap on the facts the machine shows, $1 being yes on the
# supported system. Sets bootstrap_packages, the packages needed in the
# policy's order, and bootstrap_outcome: satisfied (none needed), install,
# universe-missing (a needed package is universe's and apt does not read
# universe) or unsupported (another system needs something).
bootstrap_decide() {
    bootstrap_packages=
    bootstrap_universe=no
    while read -r row_package row_kind row_values row_universe; do
        if [ -z "$row_package" ] || ! bootstrap_row_needed "$1" "$row_kind" "$row_values"; then
            continue
        fi
        bootstrap_packages="${bootstrap_packages:+$bootstrap_packages }$row_package"
        if [ "$row_universe" = yes ]; then
            bootstrap_universe=yes
        fi
    done <<EOF
$POLICY_BOOTSTRAP
EOF

    if [ -z "$bootstrap_packages" ]; then
        bootstrap_outcome=satisfied
    elif [ "$1" != yes ]; then
        bootstrap_outcome=unsupported
    elif [ "$bootstrap_universe" = yes ] && ! universe_enabled; then
        bootstrap_outcome=universe-missing
    else
        bootstrap_outcome=install
    fi
}

# Whether a bootstrap row of kind $2 with values $3 is missing. dpkg is read
# on the supported system ($1 yes) alone. cosign verifies the signature, so
# a verification bypass needs no row that provides it.
bootstrap_row_needed() {
    case "$2" in
        installed)
            [ "$1" = yes ] && [ "$(dpkg_status "$3")" != installed ]
            ;;
        commands)
            case ",$3," in
                *,cosign,*)
                    if skip_verify || allow_unverified; then
                        return 1
                    fi
                    ;;
            esac
            ! commands_on_path "$3"
            ;;
        *)
            return 1
            ;;
    esac
}

dpkg_status() {
    # shellcheck disable=SC2016 # dpkg-query's own format field, not the shell's
    dpkg-query -W -f='${db:Status-Status}' "$1" </dev/null 2>/dev/null || true
}

# The packages among $@ that dpkg reports installed.
installed_packages() {
    installed_list=
    for installed_candidate in "$@"; do
        if [ "$(dpkg_status "$installed_candidate")" = installed ]; then
            installed_list="${installed_list:+$installed_list }$installed_candidate"
        fi
    done
    printf '%s\n' "$installed_list"
}

# Whether one of the comma-separated commands $1 is on PATH.
commands_on_path() {
    commands_ifs="$IFS"
    IFS=,
    set -f
    for command_name in $1; do
        IFS="$commands_ifs"
        if on_path "$command_name"; then
            set +f
            return 0
        fi
    done
    IFS="$commands_ifs"
    set +f
    return 1
}

# Whether an executable file named $1 is in a PATH directory. `command -v`
# would also name a shell builtin or function.
on_path() {
    on_path_ifs="$IFS"
    IFS=:
    set -f
    for on_path_dir in $PATH; do
        if [ -n "$on_path_dir" ] && [ -f "$on_path_dir/$1" ] && [ -x "$on_path_dir/$1" ]; then
            IFS="$on_path_ifs"
            set +f
            return 0
        fi
    done
    IFS="$on_path_ifs"
    set +f
    return 1
}

# "a", "a and b", "a, b and c".
words() {
    words_text=
    while [ "$#" -gt 0 ]; do
        if [ -z "$words_text" ]; then
            words_text="$1"
        elif [ "$#" -eq 1 ]; then
            words_text="$words_text and $1"
        else
            words_text="$words_text, $1"
        fi
        shift
    done
    printf '%s\n' "$words_text"
}

# The command that runs this installer again, with the CYFR_ settings the
# person gave it after the pipe, where sh receives them.
install_command() {
    command_settings=
    add_setting CYFR_VERSION "${CYFR_VERSION:-}"
    add_setting CYFR_INSTALL_DIR "${CYFR_INSTALL_DIR:-}"
    add_setting CYFR_INSTALL_YES "${CYFR_INSTALL_YES:-}"
    add_setting CYFR_ALLOW_UNVERIFIED "${CYFR_ALLOW_UNVERIFIED:-}"
    add_setting CYFR_INSECURE_SKIP_VERIFY "${CYFR_INSECURE_SKIP_VERIFY:-}"
    printf 'curl -fsSL https://raw.githubusercontent.com/%s/main/scripts/install.sh | %ssh\n' "$GITHUB_REPO" "$command_settings"
}

add_setting() {
    if [ -z "$2" ]; then
        return
    fi
    shell_word "$2"
    command_settings="$command_settings$1=$word "
}

# Sets word to $1 as the shell reads it back as one word: as it is when
# it holds nothing the shell treats specially, else in single quotes.
shell_word() {
    case "$1" in
        ""|*[!A-Za-z0-9._/:@%+,=-]*)
            word_rest="$1"
            word=
            while :; do
                case "$word_rest" in
                    *\'*)
                        word="$word${word_rest%%\'*}'\\''"
                        word_rest="${word_rest#*\'}"
                        ;;
                    *)
                        word="'$word$word_rest'"
                        break
                        ;;
                esac
            done
            ;;
        *) word="$1" ;;
    esac
}

# Prints the words $@ as one command line.
command_line() {
    line_text=
    for line_word in "$@"; do
        shell_word "$line_word"
        line_text="${line_text:+$line_text }$word"
    done
    printf '%s\n' "$line_text"
}

# What has changed: the packages this run asked for that dpkg now reports
# installed and did not before. "Nothing was installed" before any change.
# internal/install's Completed words the same changes the same way.
completed_changes() {
    completed_list=
    for completed_package in ${requested_packages:-}; do
        case " ${packages_before:-} " in
            *" $completed_package "*) continue ;;
        esac
        if [ "$(dpkg_status "$completed_package")" = installed ]; then
            completed_list="${completed_list:+$completed_list }$completed_package"
        fi
    done
    # shellcheck disable=SC2086 # package names, one word each
    set -- $completed_list
    case "$#" in
        0) printf 'Nothing was installed\n' ;;
        *) printf 'CYFR installed %s\n' "$(words "$@")" ;;
    esac
}

refuse() {
    printf '%s\n' "$1" >&2
    exit 1
}

refuse_universe() {
    refuse "Ubuntu's $POLICY_UNIVERSE_COMPONENT archive is not enabled. Run \`$POLICY_UNIVERSE_COMMAND\`, then run \`$(install_command)\` again."
}

refuse_unsupported() {
    # shellcheck disable=SC2086 # package names, one word each
    printf '%s\n' "CYFR installs these requirements automatically on $POLICY_SYSTEM_NAME. This machine runs $(system_name) and needs $(words $bootstrap_packages). Install them, then run \`$(install_command)\` again." >&2
    case " $bootstrap_packages " in
        *" cosign "*)
            printf "cosign's installation guide is https://docs.sigstore.dev/cosign/system_config/installation/; CYFR_ALLOW_UNVERIFIED=1 installs on the checksum alone.\n" >&2
            ;;
    esac
    exit 1
}

refuse_download() {
    refuse "CYFR could not download $1 from $2. $(completed_changes). Check the connection, then run \`$(install_command)\` again."
}

refuse_no_sudo() {
    refuse "This account cannot run sudo, so CYFR cannot install $requirements. $(completed_changes). Run \`$(install_command)\` from an account that can install software."
}

# Why sudo started no root step, read from its own words as with_root_helper
# kept them: sudo-rs's, and sudo's in the C locale. Words it does not know,
# where no terminal could take a password, are sudo -n's missing password;
# internal/install's ReadSudoCause and SudoRefused read and word them alike.
refuse_sudo() {
    if sudo_said 'incorrect authentication attempt' 'incorrect password attempt' 'authentication failed'; then
        refuse "sudo did not accept the password, so CYFR cannot install $requirements. $(completed_changes). Run \`$(install_command)\` again and type this account's password."
    fi
    if sudo_said 'interactive authentication is required' 'a password is required'; then
        refuse_needs_password
    fi
    if sudo_said "i'm afraid i can't do that" 'may not run' 'is not in the sudoers' 'is not allowed to'; then
        refuse_no_sudo
    fi
    case " $elevation " in
        *" -n "*) refuse_needs_password ;;
    esac
    refuse "sudo did not run CYFR's installer, so CYFR cannot install $requirements. $(completed_changes). Run \`$(install_command)\` again once sudo works for this account."
}

refuse_needs_password() {
    refuse "sudo needs this account's password, and without a terminal there is nowhere to type it, so CYFR cannot install $requirements. $(completed_changes). Run \`$(install_command)\` in a terminal, or give this account sudo without a password prompt."
}

# Whether sudo's kept words hold one of $@, in any case.
sudo_said() {
    for said_text in "$@"; do
        if grep -i -q -F -- "$said_text" "$tmpdir/said" 2>/dev/null; then
            return 0
        fi
    done
    return 1
}

# Root's refusal $1, as the helper reported it.
# shellcheck disable=SC2086 # policy package names, one word each
refuse_root() {
    case "$1" in
        install-lock) refuse_lock "Another CYFR installation" ;;
        list-lock) refuse_lock "A package-list update" ;;
        dpkg-lock) refuse_lock "A package installation" ;;
        update)
            refuse "CYFR could not download Ubuntu's package lists. $(completed_changes). Check the connection, then run \`$(install_command)\` again."
            ;;
        install)
            refuse "CYFR could not finish installing $(words $requested_packages). $(completed_changes). Check the connection, or finish the package repair with \`sudo dpkg --configure -a\`, then run \`$(install_command)\` again."
            ;;
        interrupted)
            refuse "CYFR could not finish installing $(words $requested_packages) because an earlier package installation was interrupted. $(completed_changes). Finish it with \`sudo dpkg --configure -a\`, then run \`$(install_command)\` again."
            ;;
        mismatch)
            refuse "The copy root made for $root_dest differs from the verified download, so CYFR did not install it. $(completed_changes). Run \`$(install_command)\` again."
            ;;
        copy)
            refuse "CYFR could not install the verified cyfr at $root_dest. $(completed_changes). Check the messages above, then run \`$(install_command)\` again."
            ;;
        stopped)
            refuse "CYFR's root step stopped before it finished. $(completed_changes). Check the messages above, then run \`$(install_command)\` again."
            ;;
        *)
            refuse "CYFR's root step refused its request ($1). $(completed_changes). Run \`$(install_command)\` again."
            ;;
    esac
}

refuse_lock() {
    refuse "$1 is still running after $POLICY_LOCK_SECONDS seconds. $(completed_changes). Let it finish, then run \`$(install_command)\` again."
}

# The terminal the person answers on, opened once so each question reads the
# next answer.
tty_state=closed
tty_open() {
    case "$tty_state" in
        open) return 0 ;;
        none) return 1 ;;
    esac
    if { command exec 8<"$TTY_DEVICE"; } 2>/dev/null; then
        tty_state=open
        return 0
    fi
    tty_state=none
    return 1
}

# Asks the yes-or-no question $1 on the terminal tty_open opened; no is the
# default.
ask() {
    printf '%s [y/N] ' "$1"
    tty_answer=
    IFS= read -r tty_answer <&8 || true
    case "$tty_answer" in
        [yY]|[yY][eE][sS]) return 0 ;;
    esac
    return 1
}

# Shows root's commands for the packages $1 and the CLI at $2 and returns
# once the person agrees; every other answer refuses before anything runs
# as root. Root installing the CLI alone is no elevation and asks nothing.
agree_to_root_plan() {
    if [ -n "$2" ]; then
        # shellcheck disable=SC2086 # package names, one word each
        requirements="$(words $1 "$BINARY_NAME in ${2%/*}")"
    else
        # shellcheck disable=SC2086 # package names, one word each
        requirements="$(words $1)"
    fi
    if [ "$as_root" = no ] && ! on_path sudo; then
        refuse_no_sudo
    fi
    if [ "$as_root" = yes ] && [ -z "$1" ]; then
        return
    fi

    # shellcheck disable=SC2086 # package names, one argument each
    show_root_step "${2:--}" $1

    if [ "$approval" = yes ]; then
        printf 'CYFR_INSTALL_YES=1 approves these commands.\n'
        return
    fi
    if ! tty_open; then
        refuse "Installing $requirements needs your agreement in a terminal. Nothing was installed. Run \`$(install_command)\` in a terminal, or with CYFR_INSTALL_YES=1 after the pipe to agree to the commands it shows."
    fi
    if ! ask "Install these requirements?"; then
        refuse "You chose not to install $requirements. $(completed_changes). Run \`$(install_command)\` again when you want to continue."
    fi
}

# Shows root's step for the destination $1 (- for none) and the packages
# after it: the commands root runs, as the helper's show mode prints them
# from the very code root runs, and the command that starts it. A
# destination or package the helper refuses is refused here.
show_root_step() {
    show_dest="$1"
    shift
    if ! shown_words="$(/bin/sh -c "$(root_helper_text)" cyfr-install-helper show "$tmpdir" "$show_dest" "$@")"; then
        refuse_root arguments
    fi
    printf '\nCYFR runs these commands as root:\n'
    printf '%s\n' "$shown_words" | render_commands
    printf "flock takes CYFR's install lock, %s, open as file descriptor 9, waiting up to %s seconds for another installation to finish.\n" "$POLICY_LOCK_PATH" "$POLICY_LOCK_SECONDS"
    if [ "$#" -gt 0 ]; then
        printf 'apt-get update is tried again each second, for up to %s seconds, while another package-list update holds its lock.\n' "$POLICY_LOCK_SECONDS"
    fi
    if [ "$show_dest" != - ]; then
        printf "mktemp's name takes the place of XXXXXX, and mv runs only when sha256sum gives the verified download's SHA-256.\n"
        if [ "$#" -gt 0 ]; then
            printf 'The second flock and the commands after it run once the download passes the signature and checksum checks.\n'
        fi
    fi
    elevation_words
    # shellcheck disable=SC2086 # sudo's fixed words, one each
    printf "They run as one root step: %s <CYFR's root step> %s\n" "$(command_line $elevation /bin/sh -c)" \
        "$(command_line cyfr-install-helper run "$tmpdir" "$show_dest" "$@")"
}

# Prints, indented, the commands of the helper's show mode, which gives a
# command's words one a line and an empty line after each.
render_commands() {
    set --
    while IFS= read -r render_word || [ -n "$render_word" ]; do
        if [ -n "$render_word" ]; then
            set -- "$@" "$render_word"
        elif [ "$#" -gt 0 ]; then
            printf '  %s\n' "$(command_line "$@")"
            set --
        fi
    done
    if [ "$#" -gt 0 ]; then
        printf '  %s\n' "$(command_line "$@")"
    fi
}

# Sets elevation to the words elevate puts before root's command: none as
# root, sudo -k where a terminal can take sudo's password, and sudo -n -k,
# which asks for none, where nothing can. -k ignores a cached login, and
# cleanup's sudo -k invalidates the one this leaves.
elevation_words() {
    if [ "$as_root" = yes ]; then
        elevation=
    elif tty_open; then
        elevation='sudo -k --'
    else
        elevation='sudo -n -k --'
    fi
}

# Elevates "$@" through elevation_words' words.
elevate() {
    # shellcheck disable=SC2086 # sudo's fixed words, one each
    $elevation "$@"
}

# Runs root_helper_text as root for the destination $1 (- for none) and the
# packages before --, beside the command after it. The two talk over two
# FIFOs in the private tmpdir: the command writes requests on fd 3 and reads
# replies on fd 4. The pipeline's first element holds both FIFOs open for
# the helper's lifetime and writes "exited <status>" when the elevation
# returns, so a sudo that never starts the helper, or a helper that dies,
# still ends the command's wait; it then drains the requests until the
# command ends, so a request to a helper that died fails as a reply rather
# than as SIGPIPE. Being a pipeline element rather than a
# background job keeps the terminal's interrupt reaching sudo, and the
# pipeline returns only once sudo and its helper have exited. Their
# messages reach the terminal through tee, which keeps them in the file
# refuse_sudo reads; as an asynchronous command tee ignores the terminal's
# interrupt and ends with the last writer, before "exited" is written.
with_root_helper() {
    helper_dest="$1"
    shift
    helper_packages=
    while [ "$1" != -- ]; do
        helper_packages="${helper_packages:+$helper_packages }$1"
        shift
    done
    shift
    mkfifo "$tmpdir/req" "$tmpdir/rep" "$tmpdir/err"
    helper_text="$(root_helper_text)"
    elevation_words
    if [ "$as_root" = no ]; then
        sudo_cleanup=yes
    fi
    exec 5>&1
    # shellcheck disable=SC2094 # one FIFO a direction, each end opened once
    {
        trap 'helper_signal=1' INT TERM HUP
        helper_status=0
        tee "$tmpdir/said" <"$tmpdir/err" >&2 5>&- 6<&- 7>&- 8<&- &
        said_pid=$!
        # shellcheck disable=SC2086 # package names, one argument each
        elevate /bin/sh -c "$helper_text" cyfr-install-helper run "$tmpdir" "$helper_dest" $helper_packages \
            </dev/null >&5 2>"$tmpdir/err" 5>&- 6<&- 7>&- 8<&- || helper_status=$?
        wait "$said_pid" || :
        printf 'exited %s\n' "$helper_status" >&7
        cat <&6 >/dev/null
    } 7>"$tmpdir/rep" 6<"$tmpdir/req" | {
        # shellcheck disable=SC2094 # the other ends of the FIFOs above
        exec 4<"$tmpdir/rep" 3>"$tmpdir/req"
        trap 'exit 130' INT
        trap 'exit 143' TERM
        trap 'exit 129' HUP
        helper=running
        await_helper ready
        "$@"
    }
}

# Reads root's next reply and returns when it is $1. A refusal, or an
# elevation that ended before the reply, refuses here: before ready,
# through sudo, as sudo's own refusal.
await_helper() {
    helper_reply=
    IFS= read -r helper_reply <&4 || helper_reply="exited ?"
    case "$helper_reply" in
        "$1") return 0 ;;
        "refused "*) refuse_root "${helper_reply#refused }" ;;
        "exited 64") refuse_root arguments ;;
        "exited "*)
            if [ "$1" = ready ] && [ "$as_root" = no ]; then
                refuse_sudo
            fi
            refuse_root stopped
            ;;
        *) refuse_root "reply $helper_reply" ;;
    esac
}

# The root side, a fixed program sudo runs as /bin/sh -c with the arguments
# run DIR DEST [PACKAGE...]. Its preamble fixes root's PATH, locale, the
# lock, the deadline and the packages it accepts; nothing from the
# person's side runs as a command. It reads requests from DIR/req and
# replies on DIR/rep:
#   ready                      arguments accepted
#   packages                   apt installed PACKAGE..., under the lock
#   installed                  DEST holds the verified file, under the lock
#   refused <cause>            install-lock, list-lock, dpkg-lock, update,
#                              install, interrupted, mismatch, copy,
#                              arguments or request; then it exits
# After the packages, with a DEST, it waits without the lock for one
# request: "install DIR/<binary> <sha256>" copies that regular file into a
# root-owned temporary beside DEST, installs it by rename only when the
# copy's SHA-256 is the one sent, and "done", "abort" or the end of the
# requests installs nothing.
# With show in place of run, the person's side runs the same program for
# its preview: it touches nothing and prints each command it would run
# instead, so the commands shown are the commands root runs.
root_helper_text() {
    printf "PATH='%s'\n" "$ROOT_PATH"
    printf "lock='%s'\n" "$POLICY_LOCK_PATH"
    printf "seconds='%s'\n" "$POLICY_LOCK_SECONDS"
    printf "allowed='%s'\n" "$(bootstrap_package_names)"
    printf "binary='%s'\n" "$BINARY_NAME"
    cat <<'HELPER'
LC_ALL=C
DEBIAN_FRONTEND=noninteractive
export PATH LC_ALL DEBIAN_FRONTEND
umask 022
set -u
mode=$1
dir=$2
dest=$3
shift 3
tmp=
trap 'if [ -n "$tmp" ] && [ "$mode" = run ]; then rm -f -- "$tmp"; fi' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP

case "$dir" in
    *'
'*) exit 64 ;;
    /*) ;;
    *) exit 64 ;;
esac
case "$mode" in
    run)
        if [ ! -d "$dir" ] || [ -h "$dir" ] || [ ! -p "$dir/req" ] || [ ! -p "$dir/rep" ]; then
            exit 64
        fi
        exec 3>"$dir/rep" 4<"$dir/req" 6>&1
        ;;
    show) exec 5>&1 6>&1 ;;
    *) exit 64 ;;
esac

# Every command root runs goes through run. As root it runs the command;
# shown, it prints the command's words, one a line and an empty line
# after them, on file descriptor 5, and succeeds.
run() {
    if [ "$mode" = show ]; then
        printf '%s\n' "$@" '' >&5
        return 0
    fi
    "$@"
}

reply() {
    if [ "$mode" = run ]; then
        printf '%s\n' "$1" >&3
    fi
}

say() {
    if [ "$mode" = run ]; then
        printf '%s\n' "$1"
    fi
}

refuse() {
    reply "refused $1"
    exit 1
}

case "$dest" in
    *'
'*) refuse arguments ;;
    -) ;;
    /*/"$binary")
        if [ ! -d "${dest%/*}" ]; then
            refuse arguments
        fi
        ;;
    *) refuse arguments ;;

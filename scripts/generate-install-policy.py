"""Write the install policy block of scripts/install.sh from the policy file.

Usage: python3 -I scripts/generate-install-policy.py [--check] [--policy FILE] [--script FILE]

The policy (FILE, by default apps/codex/internal/install/policy.json) is the
one definition of the system the installer prepares automatically, its
bootstrap packages, the CLI's install path, the install lock and sudo's
words for why it ran nothing. The install
script cannot read JSON before its own tools exist, so it carries the values
it needs as shell assignments between its BEGIN and END lines, which this
writes and nothing else in the script restates or assigns. `--check`
changes nothing and exits 1 naming the drift when the block differs from
what this would write. A line outside the block that assigns a POLICY_
name (NAME=, ${NAME=} or ${NAME:=}, or read, for, getopts, local or unset
naming it) would override the block, so either run exits 1 naming it and
writes nothing. A policy value outside its grammar exits 2 and writes
nothing: each value is placed in single quotes and some reach a root shell
as arguments. sudo's words are lowercase, as they are matched in any case,
one a line in their list, so none holds a line break, and a list is never
empty, since grep reads an empty list as a word every text holds.
"""

import argparse
import difflib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POLICY = "apps/codex/internal/install/policy.json"
SCRIPT = "scripts/install.sh"
BEGIN = (
    "# BEGIN install policy, generated by scripts/generate-install-policy.py "
    "from apps/codex/internal/install/policy.json"
)
END = "# END install policy"

PACKAGE = re.compile(r"[a-z0-9][a-z0-9+.-]+")
COMMAND = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]*")
WORD = re.compile(r"[a-z0-9][a-z0-9._-]*")
ARCH = re.compile(r"[a-z0-9_]+")
TEXT = re.compile(r"[A-Za-z0-9][A-Za-z0-9 ._()/-]*")
PATH = re.compile(r"/[A-Za-z0-9._-]+(?:/[A-Za-z0-9._-]+)*")
SUDO_WORDS = re.compile(r"[a-z0-9][a-z0-9 ',.-]*")
# sudo's causes in the order they are read, each with its policy key.
SUDO_CAUSES = (
    ("POLICY_SUDO_WRONG_PASSWORD", "wrong_password"),
    ("POLICY_SUDO_NEEDS_PASSWORD", "needs_password"),
    ("POLICY_SUDO_NOT_ALLOWED", "not_allowed"),
)
# A shell assignment to a POLICY_ name: NAME= anywhere a word starts, so
# also after export or readonly and inside ${NAME=} and ${NAME:=}; or a
# builtin that sets or unsets the names it is given as words of their own.
ASSIGNS = re.compile(
    r"(?<![A-Za-z0-9_$])POLICY_[A-Za-z0-9_]*:?="
    r"|\b(?:read|for|getopts|local|unset)\b[^;&|#]*(?<=\s)POLICY_[A-Za-z0-9_]*(?=\s|;|$)"
)


class PolicyError(Exception):
    pass


def field(obj, key, where):
    if not isinstance(obj, dict) or key not in obj:
        raise PolicyError(f"{where}.{key} is missing")
    return obj[key]


def matching(value, pattern, where):
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise PolicyError(f"{where} is {value!r}, outside {pattern.pattern}")
    return value


def bootstrap_row(row, where):
    package = matching(field(row, "package", where), PACKAGE, f"{where}.package")
    kinds = [kind for kind in ("installed", "commands") if isinstance(row, dict) and kind in row]
    if len(kinds) != 1:
        raise PolicyError(f"{where} needs exactly one of installed and commands")
    if kinds[0] == "installed":
        values = [matching(row["installed"], PACKAGE, f"{where}.installed")]
    else:
        commands = row["commands"]
        if not isinstance(commands, list) or not commands:
            raise PolicyError(f"{where}.commands is not a list of commands")
        values = [matching(c, COMMAND, f"{where}.commands[{i}]") for i, c in enumerate(commands)]
    universe = field(row, "universe", where)
    if not isinstance(universe, bool):
        raise PolicyError(f"{where}.universe is {universe!r}, not true or false")
    return f"{package} {kinds[0]} {','.join(values)} {'yes' if universe else 'no'}"


def sudo_words(sudo, key):
    words = field(sudo, key, "sudo")
    if not isinstance(words, list) or not words:
        raise PolicyError(f"sudo.{key} is not a list of sudo's words")
    return [matching(w, SUDO_WORDS, f"sudo.{key}[{i}]") for i, w in enumerate(words)]


def quoted(text):
    """text in single quotes, each of its own quotes as '\\''."""
    return "'" + text.replace("'", "'\\''") + "'"


def assignments(policy):
    """The block's lines between BEGIN and END for the policy."""
    system = field(policy, "system", "policy")
    universe = field(policy, "universe", "policy")
    lock = field(policy, "lock", "policy")
    architectures = field(system, "architectures", "system")
    if not isinstance(architectures, list) or not architectures:
        raise PolicyError("system.architectures is not a list of architectures")
    bootstrap = field(policy, "bootstrap", "policy")
    if not isinstance(bootstrap, list) or not bootstrap:
        raise PolicyError("bootstrap is not a list of rows")
    sudo = field(policy, "sudo", "policy")
    seconds = field(lock, "seconds", "lock")
    if not isinstance(seconds, int) or isinstance(seconds, bool) or not 1 <= seconds <= 3600:
        raise PolicyError(f"lock.seconds is {seconds!r}, not a whole number of seconds from 1 to 3600")

    def assign(name, value):
        return f"{name}='{value}'"

    rows = [bootstrap_row(row, f"bootstrap[{i}]") for i, row in enumerate(bootstrap)]
    return [
        assign("POLICY_SYSTEM_ID", matching(field(system, "id", "system"), WORD, "system.id")),
        assign("POLICY_SYSTEM_VERSION_ID", matching(field(system, "version_id", "system"), WORD, "system.version_id")),
        assign("POLICY_SYSTEM_CODENAME", matching(field(system, "codename", "system"), WORD, "system.codename")),
        assign("POLICY_SYSTEM_NAME", matching(field(system, "name", "system"), TEXT, "system.name")),
        assign(
            "POLICY_SYSTEM_ARCHITECTURES",
            " ".join(matching(a, ARCH, f"system.architectures[{i}]") for i, a in enumerate(architectures)),
        ),
        assign("POLICY_UNIVERSE_COMPONENT", matching(field(universe, "component", "universe"), WORD, "universe.component")),
        assign("POLICY_UNIVERSE_COMMAND", matching(field(universe, "command", "universe"), TEXT, "universe.command")),
        "# One bootstrap row a line: the package, the fact that shows it present",
        "# (installed: dpkg reports the package installed, read on the supported",
        "# system alone; commands: one of the comma-separated commands is on PATH),",
        "# its values and whether only Ubuntu's universe component carries it.",
        "POLICY_BOOTSTRAP='" + "\n".join(rows) + "'",
        assign("POLICY_INSTALL_PATH", matching(field(policy, "install_path", "policy"), PATH, "install_path")),
        assign("POLICY_LOCK_PATH", matching(field(lock, "path", "lock"), PATH, "lock.path")),
        assign("POLICY_LOCK_SECONDS", str(seconds)),
        "# sudo's own words for why it ran nothing, one a line, as sudo-rs and",
        "# sudo print them with LC_ALL=C: a password refused, a password needed",
        "# and an account sudo does not allow, read in that order, in any case.",
    ] + [f"{name}={quoted(chr(10).join(sudo_words(sudo, key)))}" for name, key in SUDO_CAUSES]


def shown(path):
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the block differs, changing nothing")
    parser.add_argument("--policy", type=Path, default=ROOT / POLICY)
    parser.add_argument("--script", type=Path, default=ROOT / SCRIPT)
    args = parser.parse_args()

    try:
        policy = json.loads(args.policy.read_text(encoding="utf-8"))
        block = assignments(policy)
    except (OSError, ValueError) as e:
        print(f"{shown(args.policy)}: cannot read the policy: {e}", file=sys.stderr)
        return 2
    except PolicyError as e:
        print(f"{shown(args.policy)}: {e}", file=sys.stderr)
        return 2

    try:
        text = args.script.read_text(encoding="utf-8")
    except OSError as e:
        print(f"{shown(args.script)}: cannot read the script: {e}", file=sys.stderr)
        return 2
    lines = text.split("\n")
    if lines.count(BEGIN) != 1 or lines.count(END) != 1 or lines.index(BEGIN) > lines.index(END):
        print(f"{shown(args.script)}: needs one '{BEGIN}' line and, after it, one '{END}' line", file=sys.stderr)
        return 2
    start, end = lines.index(BEGIN) + 1, lines.index(END)
    outside = [
        f"{i + 1}: {line}"
        for i, line in enumerate(lines)
        if not start - 1 <= i <= end and not line.lstrip().startswith("#") and ASSIGNS.search(line)
    ]
    if outside:
        print(
            f"{shown(args.script)}: these lines outside the install policy block assign a policy name; "
            "the block alone sets them:",
            file=sys.stderr,
        )
        sys.stderr.writelines(line + "\n" for line in outside)
        return 1
    current = "\n".join(lines[start:end]).split("\n") if end > start else []
    wanted = "\n".join(block).split("\n")
    if current == wanted:
        return 0

    if args.check:
        print(
            f"{shown(args.script)}: the install policy block differs from {shown(args.policy)}; "
            "run python3 -I scripts/generate-install-policy.py",
            file=sys.stderr,
        )
        sys.stderr.writelines(
            line + "\n"
            for line in difflib.unified_diff(
                current, wanted, f"{shown(args.script)} (block)", f"{shown(args.policy)} (generated)", lineterm=""
            )
        )
        return 1

    replaced = "\n".join(lines[:start] + wanted + lines[end:])
    mode = args.script.stat().st_mode & 0o7777
    fd, temp = tempfile.mkstemp(dir=args.script.parent, prefix=f".{args.script.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(replaced)
        os.chmod(temp, mode)
        os.replace(temp, args.script)
    except BaseException:
        os.unlink(temp)
        raise
    print(f"{shown(args.script)}: wrote the install policy block from {shown(args.policy)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
